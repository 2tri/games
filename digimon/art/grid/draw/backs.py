# 깜몬: 털 공, 귀 혹 (그늘 = 검정)
import math
c=C(36,33); c.ell(2,6,33,32,2); c.poly([(6,9),(9,0),(14,7)],2); c.poly([(21,7),(26,0),(29,9)],2)
