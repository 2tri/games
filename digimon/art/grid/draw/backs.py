from kit import C
import numpy as np
def fin(c, name, shade=True, d=3, only=(1,), post=None):
    c.t=c.t[:, ::-1].copy()                      # 좌우 반전
    if shade: c.shade(d, only=only)
    c.outline()
    if post: post(c)
    ys=np.where((c.t>=0).any(1))[0]; h=ys.max()-ys.min()+1
    c.t=c.t[:ys.max()+1-h//4]                    # 아래 1/4 잘라냄
    c.save('../%s-b.txt'%name)
    return c

