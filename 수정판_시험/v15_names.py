def plan():
    P = {}
    for k, v in PLACE.items(): P.setdefault(k, []).extend(v)
    for k, v in GEN.items(): P.setdefault(k, []).extend((n, REP[n]) for n in v)
    return P
def fix(bank, idx, s):
    if (bank, idx) in CRY:
        a, b = CRY[(bank, idx)]
        if a in s: s = s.replace(a, b)
    for old, new in plan().get((bank, idx), []):
        s = swap(s, old, new)
    return s
