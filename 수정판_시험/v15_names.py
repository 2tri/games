import re
def has_bc(ch): return '가' <= ch <= '힣' and (ord(ch) - 0xAC00) % 28 != 0
JOSA = [('이었으나', '였으나'), ('이었구나', '였구나'), ('이었다', '였다'), ('이라든가', '라든가'), ('이라도', '라도'), ('이라니', '라니'), ('이란', '란'), ('이라네', '라네'), ('이에요', '예요'), ('이랑', '랑'), ('으로', '로'), ('이다', '다'), ('이야', '야'), ('은', '는'), ('이', '가'), ('을', '를'), ('과', '와')]
def swap(text, old, new):
    out = []; i = 0
    while True:
        j = text.find(old, i)
        if j < 0: out.append(text[i:]); break
        if j > 0 and '가' <= text[j - 1] <= '힣': out.append(text[i:j + len(old)]); i = j + len(old); continue   # 다른 낱말 속
        out.append(text[i:j]); out.append(new); k = j + len(old)
        ob, nb = has_bc(old[-1]), has_bc(new[-1])
        if ob != nb:
            for a, b in JOSA:
                src, dst = (b, a) if nb else (a, b)       # 받침 없음→있음이면 b→a
                if text.startswith(src, k) and not (k + len(src) < len(text) and '가' <= text[k + len(src)] <= '힣' and src in ('이', '가', '은', '는', '을', '를', '과', '와')):
                    out.append(dst); k += len(src); break
        i = k
    return ''.join(out)
