def apply_subst(ls):
    """[(Lv, 기술)] → SUBST 적용(그 종이 이미 배우는 기술이면 다음 후보, 다 있으면 그 줄은 뺌)"""
    have = {m for _, m in ls if m not in SUBST}; out = []
    for lv, m in ls:
        if m in SUBST:
            m2 = next((c for c in SUBST[m] if c not in have and c not in SUBST), None)
            if m2 is None: continue
            m = m2
        elif any(m == x for _, x in out): continue
        have.add(m); out.append((lv, m))
    return out
