    part(s, U(E(23, 15, 11.5, 9), E(12, 18, 11, 5.6)), l, big);           // 머리 + 위턱
    for (let x = 4; x < 21; x += 3) { px(s, x, 23, W); px(s, x + 1, 23, W); px(s, x, 24, W); }  // 이빨
