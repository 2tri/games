"""아라곤 56×56 — ref/aragorn/1.jpg 구도(정면, 오른손으로 허리 칼자루를 쥠)를 격자로 읽어 따라 그림. 머리 1.3배."""
import sys; sys.path.insert(0, '../tools')
import numpy as np
from dp import *
s = Pic(56, 56)
def mail(m):            # 사슬 소매: 밝은회 바탕에 고리 점
    for y in range(s.h):
        for x in range(s.w):
            if m[y, x] and s.p[y, x] == 1 and (x + (y % 2) * 2) % 4 == 0 and y % 2 == 0: s.p[y, x] = 2
# 뒷머리 (어깨까지 늘어진 검은 머리)
part(s, U(E(29, 11, 9, 9.5), P([[20, 11], [38, 11], [39, 22], [34, 20], [24, 20], [19, 22]])), 3)
# 다리 (아래는 화면 밖으로)
part(s, U(R(22, 46, 6, 10), R(31, 46, 6, 10)), 2, shade=(1, 0, 3))
# 몸통: 짙은 가죽 웃옷
m = part(s, P([[21, 20], [37, 20], [39, 30], [38, 47], [21, 47], [20, 30]]), 2, shade=(2, 0, 3))
hatch(s, m, 3, 1, 4, -1)
fill(s, L(29, 21, 29, 46, .4), 3)                                    # 앞섶 여밈
for y in (24, 28, 32): s.px(28, y, 1); s.px(30, y, 1)                # 끈 고리
part(s, R(20, 37, 20, 3), 3)                                         # 허리띠
dots(s, 27, 37, ['000', '0.0', '000'])                               # 버클
# 왼팔(화면 왼쪽): 사슬 소매 → 가죽 팔목, 허리 옆에 늘어뜨림
m = part(s, C([[21, 21, 3.4], [18, 30, 3], [18, 38, 2.6]]), 1, shade=(-1, 1, 2)); mail(m)
part(s, C([[18, 38, 2.6], [19, 44, 2.2]]), 2, shade=(-1, 1, 3))
part(s, E(19.5, 46, 2.4, 2.2), 0, shade=(1, 1, 1))
# 칼 (허리 왼쪽에 찬 칼자루와 칼집)
part(s, L(16, 33, 12, 50, 1.4), 2, hi=(1, 0, 1))                     # 칼집
part(s, R(13, 31, 7, 2), 1, hi=(0, 1, 0))                            # 코등이
part(s, L(17, 31, 19, 26, 1), 2); part(s, E(19.5, 25.5, 1.4, 1.4), 1)   # 손잡이·자루끝
# 오른팔(화면 오른쪽): 사슬 소매 → 팔목 가죽 → 앞으로 내려 칼자루를 쥔 손
m = part(s, C([[37, 21, 3.6], [41, 29, 3.2], [40, 36, 2.8]]), 1, shade=(1, 1, 2)); mail(m)
part(s, C([[40, 36, 2.8], [37, 43, 2.4], [34, 47, 2.2]]), 2, shade=(1, 1, 3))
part(s, L(36, 42, 39, 37, .9), 3)                                     # 팔목 가죽끈
part(s, E(33, 48, 2.8, 2.4), 0, shade=(1, 1, 1))
part(s, L(33, 51, 33, 55, 1), 2); part(s, R(30, 50, 7, 1), 1)          # 단검 손잡이
# 얼굴
m = part(s, E(29, 11.5, 5.4, 6.4), 0, shade=(1, 1, 1))
fill(s, D(E(29, 11.5, 5.4, 6.4), lambda x, y: y < 13), 1)              # 아래 얼굴: 수염 그늘(밝은회)
# 앞머리: 이마를 덮고 얼굴 옆으로 흘러내린 젖은 머리칼
part(s, U(P([[21, 9], [24, 3], [30, 1], [36, 3], [38, 9], [35, 6], [32, 5], [29, 6], [26, 5], [23, 8]]),
          C([[24, 7, 1.4], [23, 13, 1.3], [22, 19, 1.2]]), C([[35, 7, 1.4], [36, 13, 1.3], [37, 19, 1.2]])), 3, line=False)
for a, b in [((26, 3), (24, 8)), ((33, 3), (35, 8)), ((29, 2), (29, 5))]: fill(s, L(*a, *b, .45), 2)   # 머리결 반사
dots(s, 25, 9, ['33.....33', '.3.....3.'])                          # 눈썹(끝이 처짐)·눈
dots(s, 28, 12, ['.1.'])                                              # 코
dots(s, 27, 14, ['.333.', '..2..'])                                   # 입·턱수염
np.save('aragorn56.npy', s.p)
