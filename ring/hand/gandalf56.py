def pat(c, x, y):
    if c == 'C':   # 회색 망토: 어두운회, 아래쪽 주름
        return 3 if (y > 37 and x % 5 == 1) else 2
    if c == 'R':   # 안쪽 긴 옷: 밝은회, 주름
        return 2 if (y > 36 and x % 6 == 3) else 1
    if c == 'B':   # 수염: 흰 바탕에 곱슬 결
        return 1 if ((x + 2 * y) % 5 == 0 or (x * 3 + y) % 7 == 0) else 0
    if c == 'M':
        return 1 if (x + y) % 2 else 0
    return -1 if c == '.' else int(c)
