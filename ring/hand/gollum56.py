"""골룸 56×56 — ref/gollum/1.jpg(흰 배경 웅크린 사진) 구도를 56칸 격자에서 읽어 따라 그림. 머리는 1.3배로 키움."""
import sys; sys.path.insert(0, '../tools')
import numpy as np
from dp import *
s = Pic(56, 56)
SK, SH = 0, 1                     # 피부 / 그늘
def body(f, d=(2, 2), per=4):     # 피부 부위: 오른쪽 아래 그늘 띠 + 빗금
    m = part(s, f, SK, shade=(d[0], d[1], SH)); hatch(s, m, d[0] + 1, d[1] + 1, per, -1, 2); return m
# 먼 쪽(오른쪽) 다리·팔
body(C([[35, 31, 3.2], [41, 30, 3], [39, 40, 2.4], [35, 48, 2.2]]))
body(U(E(34, 50, 4, 2.2), L(33, 50, 30, 53.5, 1.1, .5), L(35, 51, 34, 54.5, 1.1, .5), L(37, 51, 38, 54.5, 1.1, .5)), per=5)
body(C([[38, 23, 2.4], [42, 33, 2], [43, 46, 1.7]]))
body(U(E(43, 48, 2.6, 2), L(43, 48, 47, 51, 1, .5), L(43, 49, 45.5, 53, 1, .5), L(42, 49, 41, 53, 1, .5)), per=5)
# 몸통 (굽은 가슴, 갈비)
m = body(P([[23, 21], [31, 18], [38, 20], [41, 25], [39, 31], [34, 34], [27, 34], [22, 28]]))
for y in (24, 26, 28): paint(s, L(26, y, 30, y + 1, .6), 1); paint(s, L(34, y, 37, y - 1, .6), 1)
# 허리 천
m = part(s, P([[25, 31], [37, 30], [37, 35], [32, 40], [26, 36]]), 2, shade=(1, 1, 3))
# 가까운 쪽(왼쪽) 다리: 무릎을 위로 접음
body(C([[27, 33, 3.4], [16, 29, 3.2], [14, 38, 2.6], [17, 47, 2.4]]))
body(U(E(17, 49.5, 4, 2.2), L(15, 50, 11.5, 53, 1.1, .5), L(17, 51, 16, 54.5, 1.1, .5), L(19, 51, 21, 54, 1.1, .5)), per=5)
# 가까운 팔: 다리 앞으로 내려와 땅을 짚음
body(C([[25, 23, 2.5], [22, 35, 2.1], [21, 47, 1.8]]))
body(U(E(21, 49, 2.8, 2), L(21, 49, 17, 52, 1, .5), L(21, 50, 20, 54, 1, .5), L(22, 50, 24.5, 53.5, 1, .5)), per=5)
# 머리 (크게), 뾰족 귀
body(P([[28, 9], [21, 4], [24, 11], [28, 14]]), per=3)
body(P([[41, 8], [45, 4], [43, 11]]), per=3)
m = part(s, U(E(34, 11, 8.6, 9), E(34, 17, 6, 3)), SK, shade=(2, 2, SH))
hatch(s, m, 3, 3, 4, -1, 2)
# 얼굴 (점으로)
dots(s, 27, 8, ['.3333....3333.',
                '30003...30003',
                '30033...30333',
                '30333...30333',
                '.333.....333.'])
dots(s, 32, 14, ['.33.', '....'])                       # 콧구멍
dots(s, 28, 17, ['3333333333', '.0.0..0.0.', '..........'])   # 히죽 웃는 입과 이
dots(s, 27, 7, ['2222.....2222'])                       # 눈두덩
for (a, b) in [((33, 3), (31, 0)), ((36, 3), (37, 0)), ((30, 4), (27, 2))]:
    fill(s, L(a[0], a[1], b[0], b[1], .5), K)            # 몇 가닥 머리털
for (x, y) in [(29, 5), (30, 5), (31, 4), (28, 6)]: s.px(x, y, 0)   # 머리 반사광
np.save('gollum56.npy', s.p)
