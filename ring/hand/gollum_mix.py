"""골룸 48×48 — 참고 사진 자동 변환(머리 1.35배)을 밑그림으로, 얼굴·귀·머리털을 손으로 찍음."""
import sys; sys.path.insert(0, '../tools')
import numpy as np
from dp import Pic, dots, fill, L
t = np.load('gollum_auto48.npy')
s = Pic(48, 48); s.p = t.copy()
# 얼굴 바탕 정리 (눈 주변을 밝게)
for y in range(7, 15):
    for x in range(22, 37):
        if s.p[y, x] in (1, 2): s.p[y, x] = 1 if x > 33 else 0
# 눈두덩 그늘
dots(s, 22, 7, ['2222222.22222'])
# 왕방울 눈 두 개 (작은 동공이 정면을 봄)
dots(s, 22, 8, ['.33333.',
                '3000003',
                '3003303',
                '3003303',
                '3000003',
                '.33333.'])
dots(s, 30, 8, ['.33333.',
                '3000003',
                '3033003',
                '3033003',
                '3000003',
                '.33333.'])
dots(s, 28, 14, ['3.3'])                                  # 콧구멍
dots(s, 24, 16, ['3333333333', '.0.0..0.0.'])             # 히죽 웃는 입, 이
# 뾰족 귀
dots(s, 17, 6, ['3....', '303..', '30033', '30003', '.3333'])
dots(s, 37, 6, ['....3', '..303', '33003', '30003', '3333.'])
# 머리털 몇 가닥
for a, b in [((27, 1), (24, -2)), ((30, 0), (31, -3)), ((33, 1), (37, -1))]:
    fill(s, L(*a, *b, .45), 3)
np.save('gollum_mix48.npy', s.p)
