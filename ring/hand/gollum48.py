"""골룸 48×48 — 왼쪽(내 쪽)을 향한 3/4 옆모습. 실루엣 우선:
굽은 등 · 발뒤꿈치에 엉덩이를 붙이고 무릎을 가슴까지 · 앞으로 쭉 내민 큰 머리 · 땅을 짚은 긴 손가락.
먼 쪽 다리·팔은 거의 가려 손가락 끝만."""
import sys; sys.path.insert(0, '../tools')
import numpy as np
from dp import *
s = Pic(48, 48)
SK, SH, DK = 0, 1, 2
def skin(f, sh=(1, 1), per=4, hatch_on=False):
    m = part(s, f, SK, shade=(sh[0], sh[1], SH))
    if hatch_on: hatch(s, m, sh[0] + 1, sh[1] + 1, per, -1, DK)
    return m
# 먼 쪽 손 (무릎 뒤로 손가락 끝만)
skin(U(L(22, 37, 19, 45, 1, .5), L(24, 37, 23, 45.5, 1, .5)), hatch_on=False)
# 엉덩이·등 (발뒤꿈치 위에 앉아 둥글게 굽은 몸)
m = skin(U(E(34, 37, 7, 7), P([[25, 22], [31, 18], [38, 20], [42, 27], [42, 35], [36, 42], [27, 38], [24, 30]])), sh=(1, 2))
hatch(s, m, 2, 3, 5, -1, DK)
for x, y in [(41, 25), (42, 29), (42, 33), (39, 22)]: s.px(x, y, 3); s.px(x - 1, y + 1, 1)   # 등뼈 마디
part(s, P([[30, 39], [39, 38], [41, 43], [33, 45]]), 2, shade=(1, 1, 3))                     # 허리 천
# 가까운 다리: 정강이가 서고 무릎이 가슴 앞까지
skin(C([[36, 37, 3.8], [27, 28, 3.2]]), sh=(1, 2))        # 허벅지 (엉덩이→무릎)
skin(C([[26, 28, 3], [28, 37, 2.4], [30, 44, 2.2]]))      # 정강이 (무릎→발목)
skin(U(P([[31, 42], [32, 46.5], [17, 47], [19, 44.5], [27, 43]]),
       L(19, 46, 14.5, 46.5, 1, .45), L(20, 45, 15.5, 44.2, .9, .45)), sh=(0, 1), per=5)   # 긴 발과 발가락
# 가까운 팔: 무릎 앞으로 늘어져 땅을 짚음
skin(C([[28, 22, 2.2], [20, 30, 1.8], [14, 38, 1.6]]))
skin(U(E(13, 40, 2.4, 2), L(12, 41, 8, 46, .9, .45), L(13, 41, 11.5, 46.5, .9, .45), L(14, 41, 15, 46.5, .9, .45), L(12, 39, 8, 41, .8, .4)), sh=(0, 1), per=5)
# 귀 (뒤로 젖힌 큰 뾰족 귀)
skin(P([[24, 11], [35, 4], [31, 12], [26, 16]]), sh=(1, 1), per=3)
# 머리 (몸보다 크게, 아래로 내밀어)
m = part(s, U(E(18, 15, 9.5, 8.2), E(11, 19, 5, 3.2)), SK, shade=(1, 2, SH))
hatch(s, m, 2, 3, 4, -1, DK)
# 눈두덩 그늘 + 왕방울 눈 (가까운 눈 크게, 먼 눈은 작게)
dots(s, 5, 10, ['.2222..2222222'])
dots(s, 12, 11, ['.33333.',
                 '3000003',
                 '3330003',
                 '3330003',
                 '3000003',
                 '.33333.'])
dots(s, 5, 12, ['.333.',
                '30003',
                '33003',
                '30003',
                '.333.'])
s.px(13, 13, 0)                                             # 눈동자 반짝
dots(s, 4, 18, ['33.', '...'])                              # 콧구멍
dots(s, 5, 20, ['33333333333', '.0..0...0..'])              # 히죽 웃는 입과 이
# 머리털 몇 가닥 (뒤로 흩날림)
for a, b in [((17, 7), (24, 3)), ((20, 7), (27, 5)), ((14, 8), (16, 2)), ((22, 8), (29, 8))]: fill(s, L(*a, *b, .45), 3)
for x, y in [(12, 9), (13, 8), (14, 9), (11, 10)]: s.px(x, y, 0)   # 이마 반사광
np.save('gollum48.npy', s.p)
