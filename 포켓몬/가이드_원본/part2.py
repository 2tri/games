# ───────────────────────── 야생(관동) 파싱 ─────────────────────────
ITEM = re.compile(r'(\S+) Lv(\d+)~(\d+)(?:\((\d+)%\))?')

def parse_wild():
    places = {}; cur = None
    for line in open(S + '/wild.md', encoding='utf-8'):
        m = re.match(r'## (.+?) — 야생 파일 (\d+) \((관동|성도)\)', line)
        if m:
            name = re.sub(r'\(원래[^)]*\)', '', m.group(1)).strip()
            cur = (name, int(m.group(2)), m.group(3)); places.setdefault(name, []); places[name].append({'file': cur[1], 'zone': cur[2], 'm': {}})
            continue
        if cur and line.startswith('- '):
            label, rest = line[2:].rstrip('\n').split(': ', 1)
            places[cur[0]][-1]['m'][label] = [(a, int(b), int(c), int(d) if d else None) for a, b, c, d in ITEM.findall(rest)]
    return {k: [v for v in vs if v['zone'] == '관동'] for k, vs in places.items() if any(v['zone'] == '관동' for v in vs)}

def lv(lo, hi): return 'Lv%d' % lo if lo == hi else 'Lv%d~%d' % (lo, hi)

def walk_text(entry, top=None):
    """걷기: 아침·낮·밤을 하나로. 어느 때만 나오면 (아침)(낮)(밤) 표시."""
    seen = {}
    for t in ('아침', '낮', '밤'):
        for sp, lo, hi, p in entry['m'].get('걷기 ' + t, []):
            d = seen.setdefault(sp, {'lo': lo, 'hi': hi, 'p': p, 't': set()})
            d['lo'] = min(d['lo'], lo); d['hi'] = max(d['hi'], hi); d['t'].add(t)
            if p and (d['p'] is None or p > d['p']): d['p'] = p
    rows = sorted(seen.items(), key=lambda kv: -(kv[1]['p'] or 0))
    if top: rows = rows[:top]
    out = []
    for sp, d in rows:
        tm = '' if len(d['t']) == 3 else '(%s)' % '·'.join(sorted(d['t'], key=['아침', '낮', '밤'].index))
        out.append('%s %s%s%s' % (sp, lv(d['lo'], d['hi']), '' if d['p'] is None else ' %d%%' % d['p'], tm))
    return out

def water_text(entry):
    out = []
    for label, short in (('파도타기', '파도'), ('헌 낚싯대', '낚시(헌)'), ('좋은 낚싯대', '낚시(좋은)'), ('대단한 낚싯대', '낚시(대단한)')):
        seen = {}
        for sp, lo, hi, p in entry['m'].get(label, []):
            d = seen.setdefault(sp, [lo, hi]); d[0] = min(d[0], lo); d[1] = max(d[1], hi)
        if seen: out.append('%s: %s' % (short, ' · '.join('%s %s' % (sp, lv(*d)) for sp, d in seen.items())))
    return out

def wild_table(W):
    rows = []
    for name, es in W.items():
        for e in es:
            walk = walk_text(e); water = water_text(e)
            spx = ' '.join(a.split(' ')[0] for a in walk) + ' ' + ' '.join(re.findall(r'(\S+) Lv', ' '.join(water)))
            rows.append('<tr data-q="%s %s"><th scope="row">%s<small> 파일 %d</small></th><td class="sm">%s</td><td class="sm">%s</td></tr>' %
                        (E(name), E(spx), E(name), e['file'], E(' · '.join(walk)) or '<span class="mu">없음</span>', E(' / '.join(water)) or '<span class="mu">없음</span>'))
    return ''.join(rows)

def chapter_wild(W, names, top=8):
    out = []
    for n in names:
        for e in W.get(n, []):
            w = walk_text(e, top)
            if w: out.append((n, ' · '.join(w)))
    return out

