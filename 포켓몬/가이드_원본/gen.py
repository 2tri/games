import json, html, os
S = os.path.dirname(os.path.abspath(__file__))
DB = json.load(open(S + '/species_full.json', encoding='utf-8'))
TR = json.load(open(S + '/trainers.json', encoding='utf-8'))
CH = json.load(open(S + '/chart.json', encoding='utf-8'))
E = html.escape

TYPE_HUE = {'노말': 40, '격투': 8, '비행': 222, '독': 290, '땅': 34, '바위': 48, '벌레': 92, '고스트': 262, '강철': 200, '페어리(???)': 330,
            '불꽃': 18, '물': 208, '풀': 128, '전기': 52, '에스퍼': 342, '얼음': 184, '드래곤': 250, '악': 24}
ATTR_CLS = {'백신': 'va', '데이터': 'da', '바이러스': 'vi', '프리': 'fr', '언노운': 'fr'}

def tchip(t):
    n = '페어리' if t.startswith('페어리') else t
    return '<span class="ty" style="--h:%d">%s</span>' % (TYPE_HUE.get(t, 0), E(n))

def types(sp):
    return ''.join(tchip(t) for t in DB[sp]['type'].split('/'))

def attr(sp):
    a = DB[sp]['attr']
    return '<span class="at %s">%s</span>' % (ATTR_CLS.get(a, 'fr'), E(a))

def mult(a, defs):
    m = 1.0
    for d in defs:
        for v, l in CH.get(a, {}).items():
            if d in l: m *= float(v)
    return m

def weak_top(idx, n=3):
    ms = TR[str(idx)]; out = []
    for a in CH.keys():
        s = sum(mult(a, DB[m['sp']]['type'].split('/')) for m in ms) / len(ms)
        out.append((s, a))
    out.sort(key=lambda x: -x[0])
    return [a for s, a in out[:n]]

def attr_hint(idx):
    ms = TR[str(idx)]; cnt = {}
    for m in ms: cnt[DB[m['sp']]['attr']] = cnt.get(DB[m['sp']]['attr'], 0) + 1
    # 백신>바이러스>데이터>백신 : 상대 속성을 이기는 속성
    beats = {'바이러스': '백신', '데이터': '바이러스', '백신': '데이터'}
    best = max([k for k in cnt if k in beats], key=lambda k: cnt[k])
    parts = ' · '.join('%s %d' % (k, v) for k, v in sorted(cnt.items(), key=lambda x: -x[1]))
    return parts, beats[best], best

def party_html(idx, lvmoves=True):
    rows = []
    for m in TR[str(idx)]:
        mv = ' · '.join(m['moves'])
        rows.append('<tr><th scope="row">%s</th><td class="n">%d</td><td>%s</td><td>%s</td><td class="mv">%s</td></tr>' %
                    (E(m['sp']), m['lv'], types(m['sp']), attr(m['sp']), E(mv)))
    return ('<div class="tw"><table class="pt"><thead><tr><th>디지몬</th><th>Lv</th><th>타입</th><th>속성</th><th>기술</th></tr></thead><tbody>%s</tbody></table></div>' % ''.join(rows))

def boss_card(title, who, where, reward, idx, tip, extra=''):
    ms = TR[str(idx)]
    lv = [m['lv'] for m in ms]
    wt = weak_top(idx)
    parts, good, best = attr_hint(idx)
    ace = max(lv)
    return ('<details class="boss"><summary><span class="bt">%s</span><span class="bn">%s</span><span class="bl">%s</span>'
            '<span class="bv">에이스 Lv%d</span></summary><div class="bb">'
            '<dl class="kv"><div><dt>장소</dt><dd>%s</dd></div><div><dt>보상</dt><dd>%s</dd></div>'
            '<div><dt>속성 구성</dt><dd>%s</dd></div><div><dt>잘 먹히는 타입</dt><dd>%s <span class="sm">(타입 상성 계산)</span></dd></div></dl>'
            '%s<p class="tip"><b>공략</b> %s</p>%s</div></details>' %
            (E(title), E(who), E(where.split(' ')[0] if False else where), ace, E(where), E(reward), E(parts + ' → ' + good + ' 속성이 유리'),
             ' '.join(tchip(t) for t in wt), party_html(idx), tip, extra))

