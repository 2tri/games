def josa(n, a, b):
    c = n[-1]; o = ord(c)
    return b if 0xAC00 <= o <= 0xD7A3 and (o - 0xAC00) % 28 == 0 else a

def cond_html(c):
    k = c[0]
    if k == 'lv': return '<span class="cd">Lv%d</span>' % c[1]
    if k == 'use': return '<span class="cd">%s 사용</span>' % E(c[1])
    if k == 'held':
        extra = ' <small>(%s)</small>' % c[2] if c[2] else ''
        return '<span class="cd">%s 지니고 레벨업%s</span>' % (E(c[1]), extra)
    if k == 'move': return '<span class="cd">「%s」를 아는 채 레벨업 <small>(Lv%d에 배움)</small></span>' % (E(c[1]), c[2][0])
    if k == 'party': return '<span class="cd">파티에 %s%s 있는 채 레벨업 <small>(조그레스)</small></span>' % (E(c[1]), josa(c[1], '이', '가'))
    return ''

def evo_section():
    by = {s: [] for s in STAGE_ORDER}
    for r in EVO: by[DB[r['src']]['stage']].append(r)
    out = []
    for st in STAGE_ORDER:
        rs = by[st]
        if not rs: continue
        rows = []
        for r in rs:
            s, d = r['src'], r['dst']
            conds = ' <i>또는</i> '.join(cond_html(c) for c in r['conds'])
            rows.append('<tr data-q="%s %s"><th scope="row">%s %s</th><td><span class="ar" aria-hidden="true">→</span> <b>%s</b> %s<br><span class="sm">%s</span></td><td>%s</td></tr>'
                        % (E(s), E(d), E(s), attr(s), E(d), attr(d), E(DB[d]['stage']), conds))
        out.append('<tbody data-g><tr class="gh"><td colspan="3">%s에서 <small>%d줄</small></td></tr>%s</tbody>' % (E(st), len(rs), ''.join(rows)))
    return ''.join(out)

