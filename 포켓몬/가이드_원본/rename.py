"""공략집 글에 쓰는 이름을 게임 안 이름으로 통일 (2026-10-28).
기존 공략집(v7)은 설계표 이름을 썼는데, 롬 안 종 이름 표(글 233)에서는 13종이 다르게 나온다. 플레이어가 화면에서 보는 이름이 맞다.
(같은 칸 번호끼리 hg2_out/칸표.tsv 의 이름과 롬 이름을 짝지어 확인함. 예: 칸 305 안킬로몬 → 롬 「황금아르마몬」, 칸 306 샤코몬 → 롬 「토우몬」)
공박사·오박사는 용어표대로 모두 「겐나이」(v1.5)."""
import re
RN = {'아라크네몬': '아르케니몬', '아트라캅테리몬': '아트라캅테몬', '슈카몬': '스카몬', '베놈묘티몬': '베놈묘티스몬', '블랙워그레이몬': '블랙워그레몬',
      '아쿠이라몬': '아큐라몬', '안킬로몬': '황금아르마몬', '샤코몬': '토우몬', '할세몬': '호루스몬', '슈림몬': '수리몬', '서브마리몬': '잠수몬',
      '페가수몬': '페가수스몬', '벨리얼묘티': '벨리얼묘티몬'}
_pat = re.compile('|'.join(sorted((re.escape(k) + ('(?!몬)' if k == '벨리얼묘티' else '') for k in RN), key=len, reverse=True)))
_prof = re.compile('[공오]박사')

def rn(s):
    """종 이름만 바꾼다(여러 번 해도 같은 결과)."""
    return _pat.sub(lambda m: RN[m.group(0)], s)

def prof(s):
    """공박사·오박사 → 겐나이. 「겐나이(겐나이)」처럼 겹치면 하나로."""
    s = _prof.sub('겐나이', s)
    return re.sub(r'겐나이\s*[（(]\s*겐나이\s*[）)]', '겐나이', s)

def fix(s):
    return prof(rn(s))
